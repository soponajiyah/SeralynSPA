<script>
    const basePrice = {{ $treatment['price'] }};
    const baseDuration = {{ $treatment['duration'] }};
    const treatmentId = @json($id);

    const extraInput = document.getElementById('extraMinutes');
    const minusBtn = document.getElementById('minusBtn');
    const plusBtn = document.getElementById('plusBtn');

    const displayMinutes = document.getElementById('displayMinutes');
    const displayExtraPrice = document.getElementById('displayExtraPrice');
    const displayTotal = document.getElementById('displayTotal');

    const reserveBtn = document.getElementById('reserveBtn');

    const extraPricePerMinute = 2000;

    function rupiah(number) {
        return 'Rp' + new Intl.NumberFormat('id-ID').format(number);
    }

    function updateDuration() {
        let extraMinutes = parseInt(extraInput.value) || 0;

        extraMinutes = Math.max(0, Math.min(60, extraMinutes));

        extraInput.value = extraMinutes;

        const extraPrice = extraMinutes * extraPricePerMinute;
        const totalPrice = basePrice + extraPrice;
        const totalDuration = baseDuration + extraMinutes;

        displayMinutes.textContent = extraMinutes + ' Min';
        displayExtraPrice.textContent = rupiah(extraPrice);
        displayTotal.textContent = rupiah(totalPrice);

        const params = new URLSearchParams({
            treatment_id: treatmentId,
            duration: totalDuration,
            extra_minutes: extraMinutes,
            extra_price: extraPrice,
            total_price: totalPrice
        });

        reserveBtn.href = "{{ $reservationUrl }}" + '?' + params.toString();
    }

    minusBtn.addEventListener('click', function() {
        let value = parseInt(extraInput.value) || 0;

        if (value > 0) {
            extraInput.value = value - 10;
        }

        updateDuration();
    });

    plusBtn.addEventListener('click', function() {
        let value = parseInt(extraInput.value) || 0;

        if (value < 60) {
            extraInput.value = value + 10;
        }

        updateDuration();
    });

    extraInput.addEventListener('input', updateDuration);

    updateDuration();
</script>

